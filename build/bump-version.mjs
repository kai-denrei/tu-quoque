#!/usr/bin/env node
/* bump-version.mjs — the cache-bust runner (handover §10: no bundler).
 * Content-hashes the asset set into an 8-char token, then:
 *   1. writes VERSION + assets/js/version.js
 *   2. fingerprints same-origin CSS/JS refs in index.html with ?v=<token>
 *   3. stamps sw.js so its cache names key off the token (cache-busting ⇄ PWA)
 * Idempotent: the token is computed from content with prior stamping normalised out,
 * so re-running with no source change yields the same token and no churn. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const wr = (p, s) => fs.writeFileSync(path.join(ROOT, p), s);

// collect everything whose change should invalidate caches
const targets = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.join(dir, e.name);
    if (e.isDirectory()) walk(rel);
    else if (/\.(css|js|json|svg)$/.test(e.name) && !rel.endsWith(path.join('js', 'version.js'))) targets.push(rel);
  }
};
['assets/css', 'assets/js', 'data'].forEach(walk);
targets.push('index.html', 'offline.html', 'sw.js', 'manifest.webmanifest');

// normalise prior stamping so the hash depends only on real content
const normalise = (s) => s
  .replace(/\?v=[0-9a-f]{8}/g, '')
  .replace(/const VERSION = '[0-9a-f]{8}'/g, "const VERSION = '__CB_TOKEN__'");

const h = crypto.createHash('sha256');
for (const f of targets.sort()) h.update(f + '\0' + normalise(rd(f)));
const token = h.digest('hex').slice(0, 8);

// 1) VERSION + version.js
wr('VERSION', token + '\n');
wr('assets/js/version.js', `// generated by build/bump-version.mjs — do not edit by hand\nexport const VERSION = "${token}";\n`);

// 2) fingerprint index.html CSS/JS refs
wr('index.html', rd('index.html').replace(
  /(href|src)="(assets\/[^"?]+\.(?:css|js))(?:\?v=[0-9a-f]{8})?"/g,
  (_m, attr, url) => `${attr}="${url}?v=${token}"`));

// 3) stamp sw.js
wr('sw.js', rd('sw.js').replace(/const VERSION = '[^']*';/, `const VERSION = '${token}';`));

if (!process.argv.includes('--quiet')) console.log('cache-bust token:', token);
